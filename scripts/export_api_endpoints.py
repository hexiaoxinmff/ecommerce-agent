"""端点清单唯一事实源生成器（第十阶段 P0-2 / P0-4）。

问题：同一个事实（"后端有几个端点、分别是什么"）此前被 4 处各自维护 ——
`README.md`（16 个端点 / 11 个 router）、`docs/TEST_REPORT.md`（16 个端点）、
`docs/project-parameters.md` §3.3（手写 10 行表）、`docs/DEPLOYMENT.md`（无）。
任何一处改动都不会让另一处变红，于是它们必然漂移（实际已经漂移了）。

本模块的做法：**唯一推导源是运行中的 FastAPI app 本身**，其余全部是派生物。

    app.openapi()            → method / path / summary / security
    app.routes（递归展开）    → endpoint.__module__ / include prefix

产出：

    docs/API_ENDPOINTS.md        权威清单（完整表格，头部标注"自动生成，勿手改"）
    docs/api_endpoints.json      同一清单的机器可读版本
    其余文档中的 marker 区块      由本脚本就地重写

用法：

    python scripts/export_api_endpoints.py            # 生成 / 同步
    python scripts/export_api_endpoints.py --check     # 只校验，漂移则 exit 1

`--check` 会被 `backend/tests/test_api_endpoints_manifest.py` 复用，
因此"改了路由却没同步文档"一定会让测试变红，而不是静默漂移。
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from dataclasses import asdict, dataclass
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
BACKEND_DIR = PROJECT_ROOT / "backend"

CANONICAL_MD = PROJECT_ROOT / "docs" / "API_ENDPOINTS.md"
CANONICAL_JSON = PROJECT_ROOT / "docs" / "api_endpoints.json"

# marker 区块：本脚本只重写 BEGIN/END 之间的内容，区块外一个字节都不碰。
MARKER_BEGIN = "<!-- API-ENDPOINTS:BEGIN (generated by scripts/export_api_endpoints.py — do not edit) -->"
MARKER_END = "<!-- API-ENDPOINTS:END -->"

# 期望值：端点数变化必须是有意为之。写死在这里，改路由就会在测试里炸出来。
EXPECTED_ENDPOINT_COUNT = 18


@dataclass(frozen=True)
class Endpoint:
    """一个 HTTP 端点（唯一事实源的一行）。"""

    index: int
    router: str
    method: str
    path: str
    summary: str
    auth: bool
    auth_scheme: str
    response_model: str
    source_module: str


def _short_router(module: str) -> str:
    """`app.api.routes.schema_link` → `schema_link`。"""
    return module.rsplit(".", 1)[-1]


def _schema_model_name(schema: object) -> str:
    """从 JSON Schema 片段里取模型名（取不到返回 `—`）。"""
    if not isinstance(schema, dict):
        return "—"
    ref = schema.get("$ref")
    if isinstance(ref, str):
        return ref.rsplit("/", 1)[-1]
    for combinator in ("anyOf", "oneOf", "allOf"):
        for branch in schema.get(combinator, []) or []:
            ref = branch.get("$ref")
            if isinstance(ref, str):
                return ref.rsplit("/", 1)[-1]
    return schema.get("type", "—")


def _response_model_name(op: dict) -> str:
    """取 200/201/202 成功响应的模型名。"""
    responses = op.get("responses") or {}
    for code in ("200", "201", "202"):
        response = responses.get(code)
        if not isinstance(response, dict):
            continue
        schema = (response.get("content") or {}).get("application/json", {}).get("schema")
        name = _schema_model_name(schema)
        if name != "—":
            return name
    return "—"


def build_endpoints() -> list[Endpoint]:
    """从运行中的 FastAPI app 推导端点清单（唯一推导源）。"""
    if str(BACKEND_DIR) not in sys.path:
        sys.path.insert(0, str(BACKEND_DIR))

    from app.main import app  # noqa: PLC0415 — 必须在 sys.path 调整之后导入

    spec = app.openapi()

    # 内层路由（未加 prefix）→ 端点函数所在模块；prefix 来自 include_context。
    inner: dict[tuple[str, str], tuple[str, str]] = {}
    for route in app.routes:
        if type(route).__name__ != "_IncludedRouter":
            continue
        prefix = getattr(route.include_context, "prefix", "") or ""
        for sub in route.original_router.routes:
            methods = sorted(getattr(sub, "methods", None) or [])
            for method in methods:
                if method in ("HEAD", "OPTIONS"):
                    continue
                inner[(method, prefix + sub.path)] = (sub.endpoint.__module__, sub.endpoint.__name__)

    endpoints: list[Endpoint] = []
    for path, operations in spec["paths"].items():
        for method, op in operations.items():
            upper = method.upper()
            if upper in ("HEAD", "OPTIONS"):
                continue
            module, _func = inner.get((upper, path), ("app.api.routes.<unknown>", ""))
            security = op.get("security") or []
            schemes = sorted({name for item in security for name in item})
            endpoints.append(
                Endpoint(
                    index=0,  # 稍后按注册顺序统一编号
                    router=_short_router(module),
                    method=upper,
                    path=path,
                    summary=op.get("summary") or "",
                    auth=bool(schemes),
                    auth_scheme=", ".join(schemes) if schemes else "—",
                    response_model=_response_model_name(op),
                    source_module=module,
                )
            )

    # 注册顺序（= main.py include_router 顺序），而非字母序：读起来跟代码一致。
    order = {
        (method, path): i
        for i, (method, path) in enumerate(_registration_order())
    }
    endpoints.sort(key=lambda e: order.get((e.method, e.path), 10_000))
    return [
        Endpoint(**{**asdict(e), "index": i + 1}) for i, e in enumerate(endpoints)
    ]


def _registration_order() -> list[tuple[str, str]]:
    """按 app.routes 展开顺序返回 (METHOD, full_path)，作为稳定排序键。"""
    if str(BACKEND_DIR) not in sys.path:
        sys.path.insert(0, str(BACKEND_DIR))
    from app.main import app  # noqa: PLC0415

    ordered: list[tuple[str, str]] = []
    for route in app.routes:
        if type(route).__name__ != "_IncludedRouter":
            continue
        prefix = getattr(route.include_context, "prefix", "") or ""
        for sub in route.original_router.routes:
            for method in sorted(getattr(sub, "methods", None) or []):
                if method in ("HEAD", "OPTIONS"):
                    continue
                ordered.append((method, prefix + sub.path))
    return ordered


def manifest() -> dict:
    endpoints = build_endpoints()
    return {
        "generated_by": "scripts/export_api_endpoints.py",
        "source_of_truth": "backend/app/main.py + backend/app/api/routes/*（由 app.openapi() 与 app.routes 推导）",
        "endpoint_count": len(endpoints),
        "router_count": len({e.router for e in endpoints}),
        "auth_required_count": sum(1 for e in endpoints if e.auth),
        "public_count": sum(1 for e in endpoints if not e.auth),
        "endpoints": [asdict(e) for e in endpoints],
    }


# ---------- 渲染 ----------


def render_table(data: dict, newline: str = "\n") -> str:
    lines = [
        "| # | router | method | path | 用途 | 鉴权 | 响应模型 |",
        "|---:|---|---|---|---|---|---|",
    ]
    for e in data["endpoints"]:
        auth = "需要 Bearer" if e["auth"] else "公开"
        summary = e["summary"].replace("|", "\\|")
        lines.append(
            f"| {e['index']} | `{e['router']}` | `{e['method']}` | `{e['path']}` "
            f"| {summary} | {auth} | `{e['response_model']}` |"
        )
    return newline.join(lines)


def render_canonical_md(data: dict, newline: str = "\n") -> str:
    lines = [
        "# API 端点权威清单（唯一事实源）",
        "",
        "> **本文件由 `scripts/export_api_endpoints.py` 自动生成，请勿手改。**",
        "> 任何手改都会让 `backend/tests/test_api_endpoints_manifest.py` 变红。",
        "",
        f"- **端点总数：{data['endpoint_count']}**",
        f"- **router 数：{data['router_count']}**",
        f"- **需鉴权（Bearer）：{data['auth_required_count']}** ／ **公开：{data['public_count']}**",
        "",
        "推导源：`backend/app/main.py` 的 `include_router` 顺序 + `app.openapi()` 的 "
        "`paths` / `summary` / `security`，以及 `app.routes` 展开后的 `endpoint.__module__`。",
        "也就是说：**改代码 = 改这份清单**，没有第二个人需要记得同步。",
        "",
        "## 清单",
        "",
        render_table(data, newline),
        "",
        "## 各文档如何引用",
        "",
        "其余文档（`README.md`、`docs/API.md`、`docs/project-parameters.md`、"
        "`docs/DEPLOYMENT.md`、`docs/TEST_REPORT.md`）不各自维护数字，"
        "而是嵌入由本脚本重写的 marker 区块。",
        "",
    ]
    return newline.join(lines)


def render_count_block(
    data: dict,
    newline: str,
    *,
    with_table: bool = False,
    link: str = "docs/API_ENDPOINTS.md",
) -> str:
    head = (
        f"**API 端点：{data['endpoint_count']} 个**"
        f"（{data['router_count']} 个 router；需鉴权 {data['auth_required_count']} ／ "
        f"公开 {data['public_count']}）。权威清单见 [`{link}`]({link})。"
    )
    if not with_table:
        return head
    return newline.join([head, "", render_table(data, newline)])


# 每个"当前有效材料"要同步的位置：(相对路径, 是否内嵌完整表格, 相对链接)
SYNC_TARGETS: list[tuple[str, bool, str]] = [
    ("README.md", False, "docs/API_ENDPOINTS.md"),
    ("docs/API.md", True, "API_ENDPOINTS.md"),
    ("docs/project-parameters.md", False, "API_ENDPOINTS.md"),
    ("docs/DEPLOYMENT.md", False, "API_ENDPOINTS.md"),
    ("docs/TEST_REPORT.md", False, "API_ENDPOINTS.md"),
]


def _dominant_newline(raw: bytes) -> str:
    return "\r\n" if raw.count(b"\r\n") > raw.count(b"\n") / 2 else "\n"


def _replace_block(text: str, body: str, newline: str) -> tuple[str, bool]:
    """把 marker 区块之间的内容换成 body。返回 (新文本, 是否发生改动)。"""
    pattern = re.compile(
        re.escape(MARKER_BEGIN) + r".*?" + re.escape(MARKER_END),
        re.DOTALL,
    )
    replacement = newline.join([MARKER_BEGIN, body, MARKER_END])
    if not pattern.search(text):
        return text, False
    new_text, count = pattern.subn(lambda _m: replacement, text)
    return new_text, new_text != text and count == 1


def sync(check: bool) -> tuple[bool, list[str]]:
    """生成/校验全部派生物。返回 (是否一致, 消息列表)。"""
    data = manifest()
    messages: list[str] = []
    ok = True

    if data["endpoint_count"] != EXPECTED_ENDPOINT_COUNT:
        ok = False
        messages.append(
            f"FAIL 端点数为 {data['endpoint_count']}，期望 {EXPECTED_ENDPOINT_COUNT}"
            "（若是有意新增路由，请同步更新 EXPECTED_ENDPOINT_COUNT）"
        )

    # 1) 权威文件（整文件生成，用 \n）
    for path, content in (
        (CANONICAL_MD, render_canonical_md(data)),
        (CANONICAL_JSON, json.dumps(data, ensure_ascii=False, indent=2) + "\n"),
    ):
        payload = content.encode("utf-8")
        current = path.read_bytes() if path.exists() else b""
        if current != payload:
            if check:
                ok = False
                messages.append(f"FAIL {path.relative_to(PROJECT_ROOT)} 与生成结果不一致")
            else:
                path.write_bytes(payload)
                messages.append(f"WROTE {path.relative_to(PROJECT_ROOT)}")

    # 2) 其余文档的 marker 区块（就地替换，保留原换行风格）
    for rel, with_table, link in SYNC_TARGETS:
        path = PROJECT_ROOT / rel
        if not path.exists():
            ok = False
            messages.append(f"FAIL {rel} 不存在")
            continue
        raw = path.read_bytes()
        text = raw.decode("utf-8")
        newline = _dominant_newline(raw)
        body = render_count_block(data, newline, with_table=with_table, link=link)
        new_text, changed = _replace_block(text, body, newline)
        if MARKER_BEGIN not in text:
            ok = False
            messages.append(f"FAIL {rel} 缺少 API-ENDPOINTS marker 区块")
            continue
        if changed:
            if check:
                ok = False
                messages.append(f"FAIL {rel} 的 marker 区块内容与生成结果不一致")
            else:
                path.write_bytes(new_text.encode("utf-8"))
                messages.append(f"WROTE {rel}")

    if ok and not messages:
        messages.append("OK 全部派生物与事实源一致")
    return ok, messages


def fingerprint() -> str:
    """清单指纹：写进报告用，便于第三方复核。"""
    payload = json.dumps(manifest(), ensure_ascii=False, sort_keys=True).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()[:8]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="生成/校验 API 端点唯一事实源")
    parser.add_argument("--check", action="store_true", help="只校验，不写文件；漂移则 exit 1")
    parser.add_argument("--fingerprint", action="store_true", help="打印清单指纹后退出")
    args = parser.parse_args(argv)

    if args.fingerprint:
        print(fingerprint())
        return 0

    ok, messages = sync(check=args.check)
    for message in messages:
        print(message)
    print(f"清单指纹 {fingerprint()}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
